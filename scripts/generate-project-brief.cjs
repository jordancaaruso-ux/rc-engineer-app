#!/usr/bin/env node
/**
 * Builds docs/PROJECT_BRIEF.md — the single file uploaded to the claude.ai Project.
 *
 * WHY THIS EXISTS. The claude.ai Project is blind: it cannot open this repo, so someone has to
 * type the facts in. Typed facts rot. Three hand-written briefing files (PROJECT_CONTEXT.md,
 * CLAUDE_PROJECT_CONTEXT.md, CLAUDE_PROJECT_INSTRUCTIONS.md — 2,156 lines between them) died that
 * way: the biggest was 178 commits and 1,148 changed files behind reality, still stating every
 * figure with total confidence. Nothing could tell you which lines had gone bad by reading them.
 *
 * So the brief is split by who can write it. Everything a machine can measure is measured here,
 * every time. Everything a machine could never know — why a decision was made, what was tried and
 * rejected, how to talk to the founder — is hand-written in docs/project-brief/durable.md and
 * passed through untouched.
 *
 * "Is the brief stale?" stops being an audit and becomes: re-run this, re-upload.
 *
 *   node scripts/generate-project-brief.cjs      (or: npm run brief)
 */
const fs = require("node:fs");
const path = require("node:path");

const ROOT = path.join(__dirname, "..");
const r = (...p) => path.join(ROOT, ...p);
const read = (p) => fs.readFileSync(r(p), "utf8");
const exists = (p) => fs.existsSync(r(p));

/** Directory entries only, sorted, excluding dotfiles. */
function dirs(rel) {
  if (!exists(rel)) return [];
  return fs
    .readdirSync(r(rel), { withFileTypes: true })
    .filter((e) => e.isDirectory() && !e.name.startsWith("."))
    .map((e) => e.name)
    .sort();
}

function files(rel, ext) {
  if (!exists(rel)) return [];
  return fs
    .readdirSync(r(rel), { withFileTypes: true })
    .filter((e) => e.isFile() && e.name.endsWith(ext))
    .map((e) => e.name)
    .sort();
}

/** Every `route.ts` under src/app, counted. */
function countRoutes(rel = "src/app", acc = { n: 0 }) {
  if (!exists(rel)) return acc.n;
  for (const e of fs.readdirSync(r(rel), { withFileTypes: true })) {
    if (e.isDirectory()) countRoutes(path.join(rel, e.name), acc);
    else if (e.name === "route.ts") acc.n += 1;
  }
  return acc.n;
}

const pkg = JSON.parse(read("package.json"));
const schema = read("prisma/schema.prisma");

const models = [...schema.matchAll(/^model\s+(\w+)\s*\{/gm)].map((m) => m[1]).sort();
const testScripts = Object.keys(pkg.scripts || {}).filter((s) => s.startsWith("test:"));
const libDirs = dirs("src/lib");
const kbFiles = files("content/vehicle-dynamics", ".md");
const kbWords = kbFiles.reduce(
  (n, f) => n + read(path.join("content/vehicle-dynamics", f)).split(/\s+/).filter(Boolean).length,
  0
);
const specDocs = files("docs", ".md").filter((f) => f !== "PROJECT_BRIEF.md");

const dep = (name) => (pkg.dependencies?.[name] || pkg.devDependencies?.[name] || "—").replace(/^\^/, "");

const durable = exists("docs/project-brief/durable.md")
  ? read("docs/project-brief/durable.md")
  : "> **Missing:** docs/project-brief/durable.md — the hand-written half was not found.\n";

const out = `# JRC Race Engineer — Project Brief

> **Generated by \`scripts/generate-project-brief.cjs\`. Do not hand-edit.**
> Everything below the line marked *Measured* is read from the repo at generation time. Everything
> above it is hand-written in \`docs/project-brief/durable.md\`. To refresh: \`npm run brief\`, then
> re-upload this file to the claude.ai Project.
>
> **If a fact here looks wrong, it is out of date, not disputed — re-run the generator.**

${durable.trim()}

---

# Measured

*Every number below was counted from the repository when this file was generated. None of it was
typed by hand, and none of it should be quoted from memory in a later conversation.*

## Stack

| | |
|---|---|
| Next.js | ${dep("next")} |
| React | ${dep("react")} |
| Prisma | ${dep("@prisma/client")} |
| NextAuth | ${dep("next-auth")} |
| Tailwind | ${dep("tailwindcss")} |
| Capacitor (iOS shell) | ${dep("@capacitor/core")} |

## Shape

| | |
|---|---|
| Domain folders in \`src/lib\` | **${libDirs.length}** |
| Prisma models | **${models.length}** |
| API routes (\`route.ts\` under \`src/app\`) | **${countRoutes()}** |
| Test scripts in \`package.json\` | **${testScripts.length}** |
| Spec documents in \`docs/\` | **${specDocs.length}** |
| Vehicle-dynamics KB | **${kbFiles.length}** files · **${kbWords.toLocaleString()}** words |

## \`src/lib\` — where the logic lives

${libDirs.map((d) => `\`${d}\``).join(" · ")}

## Prisma models

${models.map((m) => `\`${m}\``).join(" · ")}

## Vehicle-dynamics KB files

${kbFiles.map((f) => `\`${f.replace(/\.md$/, "")}\``).join(" · ")}

## Spec documents

${specDocs.map((f) => `\`${f}\``).join(" · ")}

## Test scripts

${testScripts.map((s) => `\`${s}\``).join(" · ")}
`;

fs.writeFileSync(r("docs/PROJECT_BRIEF.md"), out, "utf8");
console.log(
  `docs/PROJECT_BRIEF.md written — ${out.split("\n").length} lines ` +
    `(${libDirs.length} lib folders, ${models.length} models, ${countRoutes()} routes, ${kbFiles.length} KB files)`
);
